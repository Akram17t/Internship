function getStoredLang() {
  const stored = window.localStorage.getItem(LANG_STORAGE_KEY);
  return stored === "id" || stored === "en" ? stored : "en";
}

let currentLang = getStoredLang();

function t(key, vars) {
  const dict = I18N_STRINGS[currentLang] || I18N_STRINGS.en;
  let value = dict[key];
  if (value === undefined) value = I18N_STRINGS.en[key];
  if (value === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((name) => {
      value = value.split(`{${name}}`).join(String(vars[name]));
    });
  }
  return value;
}

function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
}

function setLang(lang) {
  const nextLang = lang === "id" ? "id" : "en";
  currentLang = nextLang;
  window.localStorage.setItem(LANG_STORAGE_KEY, nextLang);
  document.documentElement.lang = nextLang;
  applyI18n(document);
  document.dispatchEvent(new CustomEvent("ics:languagechange", { detail: { lang: nextLang } }));
}

document.documentElement.lang = currentLang;

window.I18N = {
  t,
  applyI18n,
  setLang,
  getLang: () => currentLang,
};

function syncLangToggleButtons() {
  document.querySelectorAll(".lang-toggle-option").forEach((button) => {
    const isActive = button.dataset.lang === currentLang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function bindLangToggle() {
  document.querySelectorAll(".lang-toggle-option").forEach((button) => {
    button.addEventListener("click", () => {
      if (button.dataset.lang === currentLang) return;
      setLang(button.dataset.lang);
      syncLangToggleButtons();
    });
  });
  syncLangToggleButtons();
}

// This script runs at the bottom of <body>, after the markup it targets
// already exists, so the DOM is ready to query synchronously here.
applyI18n(document);
bindLangToggle();
